LAYOUTS = {"ansi": ANSI, "iso": ISO}

# USB product ids whose Akko VIA definition is ISO
ISO_PRODUCT_IDS = {0xE4F6}


def layout_for(pid, override=None):
    """Return the key list for a keyboard, honouring an explicit choice."""
    if override:
        return LAYOUTS[override]
    return ISO if pid in ISO_PRODUCT_IDS else ANSI
